class Skill {
    constructor(name, energyCost, cooldown) {
        this.name = name;
        this.energyCost = energyCost;
        this.cooldown = cooldown;
        this.normalizedSpeed = 1.7; // Default normalized speed for abilities
        this.spender = false; // Whether this skill is a combo point spender
        this.comboPointsGenerated = 0; // Number of combo points generated by this skill
        this.triggersGcd = true; // Whether this skill triggers the global cooldown
    }

    damage() {
        // Base damage calculation, can be overridden by subclasses
        return 0; // Example base damage
    }

    cast(rogue, simulation) {
        if (rogue.energy >= this.energyCost && simulation.gcd === 0) {
            rogue.energy -= this.energyCost;
            if (this.triggersGcd) {
                simulation.setGcd();
            }
            const result = simulation.resolveAttack(this.name, "skill", this.damage());
            
            if(result.landed){
                if (this.spender) {
                    rogue.comboPoints = 0; // Reset combo points after spending
                } else {
                    rogue.comboPoints = Math.min(rogue.comboPoints + this.comboPointsGenerated, rogue.maxComboPoints);
                }
            } else {
                // If the attack didn't land, refund 80% energy cost
                rogue.energy += this.energyCost * 0.8;
            }
            
            return result;
        }
        return null;
    }
}

export class SinisterStrike extends Skill {
    constructor(rogue) {
        super("Sinister Strike", 45, 0); // Example values
        this.rogue = rogue;
        this.comboPointsGenerated = 1; // Sinister Strike generates 1 combo point
    }

    damage() {
        return this.rogue.rollWeaponDamageForSkill() + 68;
    }
}

export class Eviscerate extends Skill { 
    constructor(rogue) {
        super("Eviscerate", 35, 0);
        this.rogue = rogue;
        this.spender = true; // Eviscerate is a combo point spender
    }

    damage() {
        const modifier = this.rogue.getAttackPower() * this.rogue.comboPoints * 0.03;
        var min = modifier;
        var max = modifier;
        switch (this.rogue.comboPoints) {
            case 1:
                min = min + 224;
                max = max + 332;
                break;
            case 2:
                min = min + 394;
                max = max + 502;
                break;
            case 3:
                min = min + 564;
                max = max + 672;
                break;
            case 4:
                min = min + 734;
                max = max + 842;
                break;
            case 5:
                min = min + 904;
                max = max + 1012;
                break;
        }
        return Math.floor(Math.random() * (max - min + 1) + min);
    }
}