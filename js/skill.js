export class Rupture extends Skill {
  constructor(rogue) {
    const stats = k("rupture");
    super("rupture", "Rupture", stats.energy, stats.cooldown);
    this.aura = AURAS.rupture;
    this.rogue = rogue;
    this.spender = true; // Rupture is a combo point spender
    this.triggersGcd = true; // Rupture triggers the global cooldown
    this.attackSkill = true; // Rupture is an attack skill
    this.icon = "./img/rupture.jpg"; // Set the icon for Rupture
    this.dot = true; // Rupture is a damage over time skill
    this.bleed = true; // Rupture ticks skip armor when bleed.ignoresArmor is set
  }

  damage() {
    const comboPoints = this.rogue.comboPoints;
    const stats = k("rupture");
    // Totals, not per tick. The DoT applicator divides this by the tick count.
    const apByCp = k("rupture.apByCP");
    if (
      comboPoints < 1 ||
      comboPoints > stats.damageByCp.length ||
      comboPoints > stats.durationByCp.length ||
      comboPoints > apByCp.length
    ) {
      this.duration = 0;
      return 0;
    }
    this.duration = stats.durationByCp[comboPoints - 1];
    return (
      stats.damageByCp[comboPoints - 1] +
      this.rogue.getAttackPower() * apByCp[comboPoints - 1]
    );
  }
}

