import { k } from "../data/constants.js";
import { AURAS } from "./auras.js";

// A skill is identified by its id, the ability catalogue's id for it
// (js/abilities.js, slugify(name)). The name is for display: the page, the
// combat log and the result's per-ability breakdown. Nothing compares it.
class Skill {
  constructor(id, name, energyCost, cooldown) {
    this.id = id;
    this.name = name;
    this.energyCost = energyCost;
    // What an energyCost modifier's scope sees of this skill. A skill attacks
    // with the main hand (Simulation.attackContext reads `hand`).
    this.hand = "mainHand";
    this.costContext = Object.freeze({ ability: id });
    this.cooldown = cooldown;
    this.duration = 0;
    this.spender = false; // Whether this skill is a combo point spender
    this.comboPointsGenerated = 0; // Number of combo points generated by this skill
    // Premeditation only. Expiry removes premeditation.cpRemovedOnExpiry
    // unless a later cast adds a combo point or a finisher spends them.
    this.expiresComboPoints = false;
    this.triggersGcd = true; // Whether this skill triggers the global cooldown
    this.attackSkill = true;
    this.icon = "./img/stealth.jpg"; // Default icon, can be overridden by subclasses
    this.dot = false;
    this.bleed = false;
    // The aura (js/auras.js) a cast puts up for `duration` seconds, if any. An
    // aura on the player (haste, energy regen) is a buff, one on the target (a
    // DoT, or bonus damage taken) a debuff: the definition says which.
    this.aura = null;
  }

  damage() {
    // Subclasses that deal damage override this. A base cast deals none.
    return 0;
  }

  onCooldown(rogue, simulation) {
    return simulation.cooldowns[this.id] > 0;
  }

  cast(rogue, simulation) {
    if (this.onCooldown(rogue, simulation)) {
      return null; // Skill is on cooldown, cannot cast
    }
    // Spenders (Eviscerate, Rupture, Slice and Dice) need a combo point.
    if (this.spender && rogue.comboPoints < 1) {
      return null;
    }
    // gcd.flags: an ability on the GCD waits until it is clear. A remainder
    // within sim.tickEpsilon counts as clear, the same tolerance buffs,
    // cooldowns, DoT expiry, and weapon swings already use. Every off-GCD
    // skill skips that wait and does not start one, not only Premeditation.
    // A future off-GCD skill, such as Cold Blood, inherits this.
    // The cost after energyCost modifiers (Improved Sinister Strike). With
    // none, it is this.energyCost as it stands.
    const energyCost = simulation.modifiers.resolve(
      "energyCost",
      this.energyCost,
      this.costContext,
    );
    if (
      rogue.energy >= energyCost &&
      (simulation.gcd <= k("sim.tickEpsilon") || !this.triggersGcd)
    ) {
      rogue.energy -= energyCost;
      if (this.triggersGcd) {
        simulation.setGcd();
      }

      let result = null;

      if (this.attackSkill) {
        if (this.dot) {
          // DoTs log the application with no immediate damage. Ticks use the resolved amount.
          result = simulation.resolveDotAttack(
            this,
            "skill",
            this.damage(),
            this.duration,
            this.bleed,
          );
        } else {
          result = simulation.resolveAttack(this, "skill", this.damage());
        }
      } else {
        simulation.recordAbility(this, "cast");
        simulation.addCombatEvent(
          this.name,
          "skill",
          0,
          "Cast",
          "cast",
          this.icon,
        );
      }

      if (result && !result.landed) {
        // A miss refunds skill.missEnergyRefund of the energy and does not start the cooldown.
        rogue.energy += energyCost * k("skill.missEnergyRefund");
        return result; // Return the result of the attack attempt
      }

      if (this.spender) {
        rogue.comboPoints = 0; // Reset combo points after spending
        rogue.clearPremeditation();
      } else {
        const before = rogue.comboPoints;
        rogue.comboPoints = Math.min(
          rogue.comboPoints + this.comboPointsGenerated,
          rogue.maxComboPoints,
        );
        const gained = rogue.comboPoints - before;
        if (this.expiresComboPoints) {
          rogue.armPremeditation();
        } else if (gained > 0) {
          rogue.clearPremeditation();
        }
      }

      //  Put this attack on CD
      if (this.cooldown > 0) {
        simulation.cooldowns[this.id] = this.cooldown; // Set the skill's cooldown
      }

      if (this.duration > 0 && this.aura) {
        simulation.applyAura(this.aura, {
          duration: this.duration,
          icon: this.icon,
        });
      }

      return result;
    }
    return null;
  }
}

export class SinisterStrike extends Skill {
  constructor(rogue) {
    const stats = k("sinisterStrike");
    super("sinister-strike", "Sinister Strike", stats.energy, stats.cooldown);
    this.rogue = rogue;
    this.comboPointsGenerated = stats.comboPoints; // sinisterStrike.comboPoints
    this.icon = "./img/sinister_strike.jpg"; // Set the icon for Sinister Strike
  }

  damage() {
    return (
      this.rogue.rollWeaponDamageForSkill() + k("sinisterStrike").bonusDamage
    );
  }
}

export class Eviscerate extends Skill {
  constructor(rogue) {
    const stats = k("eviscerate");
    super("eviscerate", "Eviscerate", stats.energy, stats.cooldown);
    this.rogue = rogue;
    this.spender = true; // Eviscerate is a combo point spender
    this.icon = "./img/eviscerate.jpg"; // Set the icon for Eviscerate
  }

  damage() {
    const comboPoints = this.rogue.comboPoints;
    const modifier =
      this.rogue.getAttackPower() * comboPoints * k("eviscerate.apPerCP");
    let min = modifier;
    let max = modifier;
    const bands = k("eviscerate").damageByCp;
    if (comboPoints >= 1 && comboPoints <= bands.length) {
      min += bands[comboPoints - 1].min;
      max += bands[comboPoints - 1].max;
    }
    return Math.floor(this.rogue.random() * (max - min + 1) + min);
  }
}

