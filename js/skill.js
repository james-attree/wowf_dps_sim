export class SliceAndDice extends Skill {
  constructor(rogue) {
    const stats = k("sliceAndDice");
    super("slice-and-dice", "Slice and Dice", stats.energy, stats.cooldown);
    this.aura = AURAS.sliceAndDice;
    this.rogue = rogue;
    this.spender = true; // Slice and Dice is a combo point spender
    this.attackSkill = false; // Slice and Dice is not an attack skill
    this.icon = "./img/slice_and_dice.jpg"; // Set the icon for Slice and Dice
  }

  cast(rogue, simulation) {
    const durations = k("sliceAndDice").durationByCp;
    if (rogue.comboPoints >= 1 && rogue.comboPoints <= durations.length) {
      this.duration = durations[rogue.comboPoints - 1];
    }

    return super.cast(rogue, simulation);
  }
}

// Main-hand type "dagger" uses weaponMultiplier.dagger. Every other type uses other.
function mainHandWeaponMultiplier(stats, rogue) {
  const multipliers = stats.weaponMultiplier;
  if (rogue.weapons.mainHand.type === "dagger") {
    return multipliers.dagger;
  }
  return multipliers.other;
}

