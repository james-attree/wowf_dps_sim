export class Rupture extends Skill {
  constructor(rogue) {
    const stats = k("rupture");
    super("Rupture", stats.energy, stats.cooldown);
    this.rogue = rogue;
    this.spender = true; // Rupture is a combo point spender
    this.triggersGcd = true; // Rupture triggers the global cooldown
    this.attackSkill = true; // Rupture is not an attack skill
    this.icon = "./img/rupture.jpg"; // Set the icon for Rupture
    this.dot = true; // Rupture is a damage over time skill
  }

  damage() {
    const comboPoints = this.rogue.comboPoints;
    const stats = k("rupture");
    let baseDamage = 0;
    let duration = 0;
    let apScaling = k("rupture.apAtZeroCp");
    if (comboPoints >= 1 && comboPoints <= stats.damageByCp.length) {
      baseDamage = stats.damageByCp[comboPoints - 1];
      duration = stats.durationByCp[comboPoints - 1];
      apScaling = k("rupture.apByCP")[comboPoints - 1];
    }
    this.duration = duration;
    return baseDamage + this.rogue.getAttackPower() * apScaling;
  }
}

