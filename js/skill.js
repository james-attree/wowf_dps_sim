import { k } from "../data/constants.js";

class Skill {
  constructor(name, energyCost, cooldown) {
    this.name = name;
    this.energyCost = energyCost;
    this.cooldown = cooldown;
    this.duration = 0;
    this.normalizedSpeed = k("normalizedSpeed.dagger"); // Default normalized speed for abilities
    this.spender = false; // Whether this skill is a combo point spender
    this.comboPointsGenerated = 0; // Number of combo points generated by this skill
    this.triggersGcd = true; // Whether this skill triggers the global cooldown
    this.attackSkill = true;
    this.icon = "./img/stealth.jpg"; // Default icon, can be overridden by subclasses
    this.dot = false;
  }

  damage() {
    // Base damage calculation, can be overridden by subclasses
    return 0; // Example base damage
  }

  onCooldown(rogue, simulation) {
    return simulation.cooldowns[this.name] > 0;
  }

  cast(rogue, simulation) {
    if (this.onCooldown(rogue, simulation)) {
      return null; // Skill is on cooldown, cannot cast
    }
    // Eviscerate, Rupture, and Slice and Dice need at least 1 combo point.
    if (this.spender && rogue.comboPoints < 1) {
      return null;
    }
    if (rogue.energy >= this.energyCost && simulation.gcd === 0) {
      rogue.energy -= this.energyCost;
      if (this.triggersGcd) {
        simulation.setGcd();
      }

      let result = null;

      if (this.attackSkill) {
        if (this.dot) {
          // For DoT skills, we can log the application of the DoT without calculating immediate damage
          result = simulation.resolveDotAttack(
            this.name,
            "skill",
            this.damage(),
            this.duration,
            this.icon,
          );
        } else {
          result = simulation.resolveAttack(
            this.name,
            "skill",
            this.damage(),
            this.icon,
          );
        }
      } else {
        simulation.addCombatEvent(
          this.name,
          "skill",
          0,
          "Cast",
          "cast",
          this.icon,
        );
      }

      if (result && !result.landed) {
        // If the attack didn't land, refund part of the energy cost and don't put it on CD
        rogue.energy += this.energyCost * k("skill.missEnergyRefund");
        return result; // Return the result of the attack attempt
      }

      if (this.spender) {
        rogue.comboPoints = 0; // Reset combo points after spending
      } else {
        rogue.comboPoints = Math.min(
          rogue.comboPoints + this.comboPointsGenerated,
          rogue.maxComboPoints,
        );
      }

      //  Put this attack on CD
      if (this.cooldown > 0) {
        simulation.cooldowns[this.name] = this.cooldown; // Set the skill's cooldown
      }

      if (this.duration > 0) {
        simulation.activeBuffs[this.name] = {
          duration: this.duration,
          icon: this.icon,
        };
      }

      return result;
    }
    return null;
  }
}

export class SinisterStrike extends Skill {
  constructor(rogue) {
    const stats = k("sinisterStrike");
    super("Sinister Strike", stats.energy, stats.cooldown);
    this.rogue = rogue;
    this.comboPointsGenerated = stats.comboPoints; // Sinister Strike generates 1 combo point
    this.icon = "./img/sinister_strike.jpg"; // Set the icon for Sinister Strike
  }

  damage() {
    return (
      this.rogue.rollWeaponDamageForSkill() + k("sinisterStrike").bonusDamage
    );
  }
}

export class Eviscerate extends Skill {
  constructor(rogue) {
    const stats = k("eviscerate");
    super("Eviscerate", stats.energy, stats.cooldown);
    this.rogue = rogue;
    this.spender = true; // Eviscerate is a combo point spender
    this.icon = "./img/eviscerate.jpg"; // Set the icon for Eviscerate
  }

  damage() {
    const comboPoints = this.rogue.comboPoints;
    const modifier =
      this.rogue.getAttackPower() * comboPoints * k("eviscerate.apPerCP");
    let min = modifier;
    let max = modifier;
    const bands = k("eviscerate").damageByCp;
    if (comboPoints >= 1 && comboPoints <= bands.length) {
      min += bands[comboPoints - 1].min;
      max += bands[comboPoints - 1].max;
    }
    return Math.floor(Math.random() * (max - min + 1) + min);
  }
}

